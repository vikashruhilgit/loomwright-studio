// The component gallery (phase 5, item 08 "app primitives"): every state of
// the eight primitives (Button, Badge, Input, StatusDot, Dialog, List, Card,
// Toast) rendered in the real Electron renderer, the behaviours jsdom cannot
// prove (scroll anchoring, no-shift toasts, the dialog focus trap, reduced
// motion), and one screenshot per component per theme.
//
// There is no gallery seam in the app (the shell blocks navigation and its
// entry points belong to item 01), so this spec builds its own: in beforeAll
// it writes a real `index.html` + `entry.tsx` into the gitignored
// `app/node_modules/.cache/components-gallery/` (so bare imports such as
// `react` resolve by walking up to `app/node_modules`), builds them with
// Vite's JS API and `configFile: false` (so `app/vite.config.ts` and the app's
// `dist/` are never touched), and launches a throwaway Electron main that
// `loadFile`s the result.
//
// Screenshots: with `PRIMITIVES_EVIDENCE=1` they are written to the committed
// evidence dir `docs/evidence/phase-5-polish/components/primitives/`;
// otherwise to Playwright's per-test output dir, so CI and other lanes' e2e
// runs never dirty tracked files. The spec asserts behaviour, never pixels:
// fonts differ between macOS and the ubuntu CI run.
