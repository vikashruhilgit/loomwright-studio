test("screenshots of every component in light and dark mode", async ({}, testInfo) => {
  test.setTimeout(90_000);
  const evidence = process.env.PRIMITIVES_EVIDENCE === "1";
  if (evidence) mkdirSync(EVIDENCE_DIR, { recursive: true });
  await page.emulateMedia({ reducedMotion: "reduce" });
  const ground = () => page.evaluate(() => getComputedStyle(document.body).backgroundColor);
  const grounds: string[] = [];
  for (const theme of THEMES) {
    await setTheme(page, theme);
    await settle(page);
    grounds.push(await ground());
    for (const [name] of COMPONENTS) {
      const file = `${name}-${theme}.png`;
      const path = evidence ? join(EVIDENCE_DIR, file) : testInfo.outputPath(file);
      await page.getByTestId(`gallery-${name}`).screenshot({ path, animations: "disabled" });
      expect(statSync(path).size, `${file} was written`).toBeGreaterThan(1000);
    }
  }
  // Non-vacuous: the dark tokens really applied.
  expect(grounds[0]).not.toBe(grounds[1]);
});
