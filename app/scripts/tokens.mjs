#!/usr/bin/env node
// Generates app/src/styles/tokens.css from docs/design/tokens.json, the
// approved design tokens (DESIGN.md). The CSS is checked in and a test pins it
// byte for byte against this script's output, so the two can never drift:
//
//   node app/scripts/tokens.mjs           print the CSS on stdout
//   node app/scripts/tokens.mjs --write   (npm run tokens) rewrite app/src/styles/tokens.css
//
// Mechanism only: every value comes from tokens.json. Names map 1:1 to custom
// properties (`ground` -> `--ground`); a `.` in a name, not legal in a CSS
// identifier, becomes `-` (`space-0.5` -> `--space-0-5`). An alias value
// `{accent}` becomes `var(--accent)`. Light values go on `:root`; dark ones
// on `:root` under `prefers-color-scheme: dark` (unless the window pins
// `data-theme="light"`) and under `:root[data-theme="dark"]`, the mockup's
// own switch (docs/design/mockups/gui-v1.html).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const TOKENS_JSON = fileURLToPath(new URL("../../docs/design/tokens.json", import.meta.url));
const TOKENS_CSS = fileURLToPath(new URL("../src/styles/tokens.css", import.meta.url));

/** `name` as a custom property. */
function prop(name) {
  if (typeof name !== "string" || !/^[a-z][a-z0-9.-]*$/.test(name)) throw new TypeError(`tokens.json: bad token name ${JSON.stringify(name)}`);
  return `--${name.replace(/\./g, "-")}`;
}

/** A scalar value as CSS: `{alias}` -> `var(--alias)`. */
function cssValue(value) {
  if (typeof value === "number") return String(value);
  if (typeof value !== "string" || value === "") throw new TypeError(`tokens.json: bad token value ${JSON.stringify(value)}`);
  const alias = /^\{([a-z][a-z0-9.-]*)\}$/.exec(value);
  return alias === null ? value : `var(${prop(alias[1])})`;
}

/** A token's value for one theme: themed values are `{light, dark}`; a plain value is the same in both. */
function themed(value, theme) {
  if (typeof value === "object" && value !== null) {
    if (!(theme in value)) throw new TypeError(`tokens.json: a themed value has no ${theme}`);
    return { value: value[theme], themed: true };
  }
  return { value, themed: false };
}

function tokensOf(json, section) {
  const tokens = json[section]?.tokens;
  if (!Array.isArray(tokens)) throw new TypeError(`tokens.json: ${section}.tokens is not a list`);
  return tokens;
}

/** The CSS for `json` (a parsed tokens.json). Pure: the same input always gives the same bytes. */
export function generateTokensCss(json) {
  const light = [];
  const dark = [];

  // Colour, then the other themed sections (shadow), each light first.
  for (const section of ["color", "shadow"]) {
    for (const token of tokensOf(json, section)) {
      const l = themed(token.value, "light");
      light.push(`  ${prop(token.name)}: ${cssValue(l.value)};`);
      // Aliases resolve through var(), so only themed values are repeated for dark.
      if (l.themed) dark.push(`    ${prop(token.name)}: ${cssValue(themed(token.value, "dark").value)};`);
    }
  }

  const families = json.type?.families;
  if (typeof families !== "object" || families === null) throw new TypeError("tokens.json: type.families is missing");
  for (const [name, stack] of Object.entries(families)) light.push(`  ${prop(`font-${name}`)}: ${cssValue(stack)};`);

  const groups = json.type?.groups;
  if (!Array.isArray(groups)) throw new TypeError("tokens.json: type.groups is not a list");
  for (const group of groups) {
    for (const style of group.styles) {
      const base = `type-${style.name}`;
      if (!(group.family in families)) throw new TypeError(`tokens.json: type group ${group.name} names an unknown family`);
      light.push(`  ${prop(`${base}-family`)}: var(${prop(`font-${group.family}`)});`);
      light.push(`  ${prop(`${base}-size`)}: ${cssValue(style.fontSize)};`);
      light.push(`  ${prop(`${base}-line`)}: ${cssValue(style.lineHeight)};`);
      light.push(`  ${prop(`${base}-weight`)}: ${cssValue(style.fontWeight)};`);
      if (style.letterSpacing !== undefined) light.push(`  ${prop(`${base}-tracking`)}: ${cssValue(style.letterSpacing)};`);
    }
  }

  // Unthemed scales: spacing and the layout widths, radius, duration, easing.
  for (const section of ["spacing", "radius", "duration", "easing"]) {
    for (const token of tokensOf(json, section)) light.push(`  ${prop(token.name)}: ${cssValue(token.value)};`);
  }

  const header = `/* Generated by app/scripts/tokens.mjs from docs/design/tokens.json (${json.name}, version ${json.version}). Do not edit: run \`npm run tokens\`. */`;
  return [
    header,
    ":root {",
    "  color-scheme: light;",
    ...light,
    "}",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    "    color-scheme: dark;",
    ...dark,
    "  }",
    "}",
    ':root[data-theme="dark"] {',
    "  color-scheme: dark;",
    ...dark.map((line) => line.slice(2)),
    "}",
    "",
  ].join("\n");
}

/** The CSS for the checked-in tokens.json. */
export function generateFromRepo() {
  return generateTokensCss(JSON.parse(readFileSync(TOKENS_JSON, "utf8")));
}

const invokedDirectly = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1];
if (invokedDirectly) {
  const css = generateFromRepo();
  if (process.argv.includes("--write")) writeFileSync(TOKENS_CSS, css);
  else process.stdout.write(css);
}
